const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const link = (url, label) => url ? `<a href="${escape(url)}" target="_blank" rel="noopener noreferrer">${escape(label)}</a>` : escape(label);
export function renderAssetCredits() {
  return CREDIT_GROUPS.map(group => `<h3>${escape(group.title)}</h3><dl class="gs-credit-list">${group.entries.map(e =>
    `<dt>${escape(e.name)}</dt><dd>${escape(e.creator)}<br>${link(e.source, e.source ? 'Original source' : 'Source not recorded')} · ${link(e.licenseUrl,e.license)}${e.note ? `<br><small>${escape(e.note)}</small>` : ''}</dd>`
  ).join('')}</dl>`).join('');
}
